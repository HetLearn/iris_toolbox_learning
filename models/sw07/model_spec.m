function spec = model_spec()
% MODEL_SPEC  Package contract for the re-estimated Smets-Wouters (2007) model.
%
% See docs/DESIGN.md sec. 2. Paths are relative to spec.folder. Needs IRIS on
% the path (qq).

spec = struct();
spec.name = 'sw07';
spec.folder = fileparts(mfilename('fullpath'));
spec.model_file = 'sw07.model';
spec.params = 'sw07_params';
spec.sstate = '';
spec.linear = true;
spec.assign = struct();
spec.database = 'data/sw07_database.csv';
spec.filter_range = [qq(1965,1), qq(2026,2)];
spec.observables = {'dy', 'dc', 'dinve', 'dw', 'labobs', 'pinfobs', 'robs'};

% Policy (DESIGN 2, 13): the Taylor rule (matched by its exact label) is
% switched off under Ramsey policy (policy.mode = 'ramsey'). Targets in
% annualised percent (inflation, policy rate and its change) and the output
% gap y - yf. The discount is that of expected inflation in the Phillips
% curve, cbetabar*cgamma.
spec.policy = struct( ...
    'instrument', 'r', ...
    'rule_label', 'Monetary policy rule, Taylor rule on the output gap y-yf', ...
    'targets', struct('pinf', '4*pinf', 'ygap', 'y - yf', 'r', '4*r', 'dr', '4*(r - r{-1})'), ...
    'discount', '$cbetabar$*$cgamma$');

% Reporting (DESIGN.md sec. 10): model units are % q/q (robs % per quarter,
% labobs 100 x log); reports multiply by scale.
report = struct();
report.labels = struct( ...
    'dy',      'Output growth', ...
    'dc',      'Consumption growth', ...
    'dinve',   'Investment growth', ...
    'dw',      'Real wage growth', ...
    'labobs',  'Hours worked', ...
    'pinfobs', 'Inflation (GDP deflator)', ...
    'robs',    'Federal funds rate');
report.units = struct( ...
    'dy',      '% q/q annualised, per capita', ...
    'dc',      '% q/q annualised, per capita', ...
    'dinve',   '% q/q annualised, per capita', ...
    'dw',      '% q/q annualised', ...
    'labobs',  '100 x log, demeaned', ...
    'pinfobs', '% q/q annualised', ...
    'robs',    '% annualised');
report.scale = struct( ...
    'dy', 4, 'dc', 4, 'dinve', 4, 'dw', 4, ...
    'labobs', 1, 'pinfobs', 4, 'robs', 4);
spec.report = report;

end
